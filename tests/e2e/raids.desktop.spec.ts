import { test, expect } from '@playwright/test';
import { encodeEconomy } from '../../src/game/economy.ts';
import { raidFixture } from './raid-fixture.ts';
import { openGame, snapshot, selectUnit, clickGround } from './helpers.ts';

test('wolf rendering, individual attack/move, pause and atomic reload', async ({ page }, info) => {
  test.setTimeout(240_000);
  await page.addInitScript(value => { if (!localStorage.getItem('world-basic-economy-v1')) localStorage.setItem('world-basic-economy-v1', value); }, encodeEconomy(raidFixture()));
  const errors = await openGame(page);
  let s = await snapshot(page); expect(s.wolves.filter(w => w.active)).toHaveLength(2);
  expect(new Set(s.wolves.map(w => w.skeleton)).size).toBe(5);
  expect(new Set(s.wolves.map(w => w.geometry)).size).toBe(1);
  expect(new Set(s.wolves.map(w => w.material)).size).toBe(1);
  await expect(page.locator('#raid-notice')).toBeVisible();
  await expect(page.locator('#loading')).toHaveCSS('opacity', '0');
  await page.screenshot({ path: info.outputPath('raid-desktop.png'), animations: 'disabled' });
  await selectUnit(page, 'infantry');
  s = await snapshot(page);
  await clickGround(page, s.economy.raids.wolves[0].position, false, .85);
  expect((await snapshot(page)).selection.resident).toBe('infantry');
  expect((await snapshot(page)).combat.units.find(u => u.id === 'infantry')!.target).toBe('wolf-1-0');
  await expect.poll(async () => (await snapshot(page)).wolves.some(w => w.clip === 'Bite'), { timeout: 30000 }).toBe(true);
  await page.screenshot({ path: info.outputPath('wolf-bite.png'), animations: 'disabled' });
  await info.attach('wolf-rendering', { body: JSON.stringify((await snapshot(page)).wolves), contentType: 'application/json' });
  await page.getByRole('button', { name: '设置', exact: true }).click();
  const frozen = await snapshot(page); await page.waitForTimeout(700);
  expect((await snapshot(page)).economy.raids).toEqual(frozen.economy.raids);
  expect((await snapshot(page)).wolves).toEqual(frozen.wolves);
  expect((await snapshot(page)).economy.seconds).toBe(frozen.economy.seconds);
  await page.getByRole('button', { name: '继续游戏', exact: true }).click();
  await clickGround(page, { x: 0, z: -9 });
  s = await snapshot(page); expect(s.selection.resident).toBe('infantry');
  expect(s.combat.units.find(u => u.id === 'infantry')).toMatchObject({ order: 'move', target: undefined });
  await page.getByRole('button', { name: '设置', exact: true }).click();
  const saved = await snapshot(page);
  await page.getByRole('button', { name: '回到主菜单', exact: true }).click(); await page.reload();
  await page.getByRole('button', { name: '继续游戏', exact: true }).click();
  await expect(page.locator('#loading')).toHaveClass(/loaded/, { timeout: 90_000 });
  const restored = await snapshot(page);
  expect(restored.economy.raids.wave).toBe(saved.economy.raids.wave);
  expect(restored.economy.raids.seed).toBe(saved.economy.raids.seed);
  expect(restored.economy.raids.wolves.map(w => w.id)).toEqual(saved.economy.raids.wolves.map(w => w.id));
  restored.economy.raids.wolves.forEach((w, i) => expect(w.hp).toBeLessThanOrEqual(saved.economy.raids.wolves[i].hp));
  expect(errors).toEqual([]);
});
