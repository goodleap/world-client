import { test, expect } from '@playwright/test';
import { openGame, snapshot } from './helpers.ts';
import { Economy } from '../../src/game/economy.ts';
import { gridPoint } from '../../src/game/world-data.ts';

test('native settings and child dialogs block gameplay, preserve actions, save to menu and stop on exit', async ({ page }, info) => {
  test.setTimeout(240_000);
  const economy = new Economy(); economy.setLeadership(false);
  const siteId = economy.placeBuilding('house', gridPoint(44, 56)).task!.target;
  await page.addInitScript(state => {
    if (!localStorage.getItem('world-basic-economy-v1')) localStorage.setItem('world-basic-economy-v1', JSON.stringify(state));
  }, economy.state);
  const errors = await openGame(page);
  const frame = (await snapshot(page)).frames;
  await page.locator('#game').dispatchEvent('wheel', { deltaX: -200, deltaY: 0, deltaMode: 0 });
  await expect.poll(async () => (await snapshot(page)).frames).toBeGreaterThan(frame);
  const site = (await snapshot(page)).objects.find(o => o.id === siteId)!;
  await page.mouse.click(site.screen.x, site.screen.y);
  await expect(page.getByRole('button', { name: '取消作业', exact: true })).toBeVisible();
  await page.keyboard.down('KeyD');
  await page.getByRole('button', { name: '设置', exact: true }).click();
  const frozen = await snapshot(page);
  expect(frozen.manualPaused).toBe(true); expect(frozen.input.dragging).toBe(false);
  await page.waitForTimeout(600);
  expect((await snapshot(page)).economy).toEqual(frozen.economy);
  expect((await snapshot(page)).residents).toEqual(frozen.residents);
  await page.locator('#settings-help').click();
  await expect(page.locator('#settings-dialog')).toBeVisible(); await expect(page.locator('#help-dialog')).toBeVisible();
  await page.getByRole('button', { name: '关闭操作说明', exact: true }).click();
  expect((await snapshot(page)).manualPaused).toBe(true);
  await page.screenshot({ path: info.outputPath('settings-desktop.png') });
  await page.getByRole('button', { name: '继续游戏', exact: true }).click();
  await page.keyboard.up('KeyD');
  await expect(page.locator('#selection-card')).toBeVisible();
  const center = (await snapshot(page)).camera.x;
  await page.waitForTimeout(300); expect((await snapshot(page)).camera.x).toBe(center);
  expect((await snapshot(page)).selection.object?.id).toBe(siteId);
  await page.getByRole('button', { name: '设置', exact: true }).click();
  // Storage failure keeps the live game and its modal intact.
  const storageWrite = await page.evaluateHandle(() => Storage.prototype.setItem);
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('storage unavailable'); }; });
  await page.getByRole('button', { name: '回到主菜单', exact: true }).click();
  await expect(page.locator('#settings-notice')).toContainText('未能保存');
  expect(await page.evaluate(() => !!window.__DEMO__)).toBe(true);
  await page.evaluate(write => { Storage.prototype.setItem = write; }, storageWrite);
  await storageWrite.dispose();
  await page.getByRole('button', { name: '回到主菜单', exact: true }).click();
  await expect(page.locator('#loading')).toHaveAttribute('data-phase', 'menu');
  await expect(page.locator('#game')).toHaveCount(0); expect(await page.evaluate(() => window.__DEMO__)).toBeUndefined();
  const saved = await page.evaluate(() => localStorage.getItem('world-basic-economy-v1'));
  await page.waitForTimeout(600); expect(await page.evaluate(() => localStorage.getItem('world-basic-economy-v1'))).toBe(saved);
  await page.getByRole('button', { name: '继续游戏', exact: true }).click();
  await expect(page.locator('#loading')).toHaveAttribute('data-phase', 'playing', { timeout: 60000 });
  expect((await snapshot(page)).economy.tasks).toHaveLength(1);
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('button', { name: '退出游戏', exact: true }).click();
  await expect(page.locator('#exit-panel')).toBeVisible(); await expect(page.locator('#game')).toHaveCount(0);
  expect(await page.evaluate(() => window.__DEMO__)).toBeUndefined();
  await page.getByRole('button', { name: '返回主菜单', exact: true }).click();
  await expect(page.getByRole('button', { name: '继续游戏', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
