import { test, expect } from '@playwright/test';
import { Economy, initialEconomy, encodeEconomy } from '../../src/game/economy.ts';
import { DEFAULT_GAME_SETUP } from '../../src/game/game-setup.ts';
import { ECONOMY_SAVE_KEY } from '../../src/game/economy-storage.ts';
import { travellingFixture } from '../story-fixture.ts';
import { openGame, snapshot, selectUnit } from './helpers.ts';

test.use({ actionTimeout: 20_000 });

test('a real NPC offers a quest, speaks, accepts a hand-in and preserves an unpaid reward through Continue', async ({ page }, info) => {
  test.setTimeout(210_000);
  const economy = new Economy(initialEconomy(391, false, DEFAULT_GAME_SETUP));
  economy.setLeadership(false); economy.state.plots[0].harvests = 1;
  const saved = encodeEconomy(economy);
  await page.addInitScript(({ key, saved }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, saved); }, { key: ECONOMY_SAVE_KEY, saved });
  const errors = await openGame(page), marker = page.locator('[data-quest-npc="farmer-leader"]');
  await expect(marker).toHaveAttribute('data-status', 'available');
  await expect(marker).toBeInViewport();
  await page.locator('#story-open').tap();
  await page.locator('#story-find-npc').tap();
  await expect(marker).toBeInViewport();
  await page.screenshot({ path: info.outputPath('npc-offers-quest.png') });
  // Pick the actual rendered character; the overhead marker is a second entry.
  await selectUnit(page, 'farmer-leader', true);
  await expect(page.locator('#story-dialog')).toHaveAttribute('data-mode', 'conversation');
  await expect(page.locator('#story-speaker')).toHaveText('农民·领头');
  await expect(page.locator('[data-speaker="farmer-leader"]')).toBeVisible();
  await expect(page.locator('#story-rewards')).toContainText('木材 6');
  await page.setViewportSize({ width: 320, height: 568 });
  await expect(page.locator('#story-accept')).toBeInViewport();
  await expect(page.locator('#story-close')).toBeInViewport();
  expect(await page.locator('#story-dialog').evaluate(dialog => getComputedStyle(dialog, '::backdrop').backdropFilter)).toBe('none');
  await expect(page.locator('#selection-info')).toHaveCSS('opacity', '0');
  await page.screenshot({ path: info.outputPath('npc-dialogue-phone.png') });
  await page.setViewportSize({ width: 844, height: 390 });
  await expect(page.locator('#story-accept')).toBeInViewport();
  await expect(page.locator('#story-close')).toBeInViewport();
  await page.screenshot({ path: info.outputPath('npc-dialogue-landscape.png') });
  await page.setViewportSize({ width: 320, height: 568 });
  await page.locator('#story-close').tap();
  expect((await snapshot(page)).economy.story!.status).toBe('available');
  await page.locator('#story-open').tap();
  await expect(page.locator('#story-accept')).not.toBeVisible();
  await expect(page.locator('#story-dialog')).toHaveAttribute('data-mode', 'journal');
  await page.locator('#story-find-npc').tap();
  await marker.tap(); await page.locator('#story-accept').tap();
  await expect(page.locator('#story-dialog')).not.toBeVisible();
  await expect(marker).toHaveAttribute('data-status', 'ready');
  expect((await snapshot(page)).economy.story!.stage).toBe('harvest');
  await marker.tap(); await page.locator('#story-report').tap();
  await expect(page.locator('#story-dialog')).toHaveAttribute('data-status', 'reward');
  expect((await snapshot(page)).economy.goods).toHaveLength(0);
  await page.screenshot({ path: info.outputPath('npc-reward-pending.png') });
  await page.locator('#story-close').tap();
  await page.locator('#settings').tap(); await page.locator('#return-menu').tap();
  await page.locator('#continue-save').tap();
  await expect(page.locator('#loading')).toHaveAttribute('data-phase', 'playing', { timeout: 90_000 });
  await expect(marker).toHaveAttribute('data-status', 'reward');
  await marker.tap(); await page.locator('#story-claim').tap();
  await expect(page.locator('#story-receipt')).toBeVisible();
  await expect(page.locator('#story-receipt')).toContainText('木材 6、石材 4');
  await expect(page.locator('#story-receipt-next')).toBeInViewport();
  const state = (await snapshot(page)).economy;
  expect(state.story!.stage).toBe('road'); expect(state.story!.status).toBe('available');
  expect(state.goods.map(g => [g.resource, g.amount])).toEqual([['wood', 6], ['stone', 4]]);
  await page.screenshot({ path: info.outputPath('npc-quest-completed.png') });
  await page.locator('#story-receipt-next').tap();
  await expect(page.locator('#story-accept')).toBeVisible();
  await expect(page.locator('#story-claim')).not.toBeVisible();
  expect(errors).toEqual([]);
});

test('the craftsman arrives before claiming, hands over the chapter reward in person, and persists through Continue', async ({ page }, info) => {
  test.setTimeout(180_000);
  const economy = travellingFixture(); economy.state.seconds = economy.state.story!.arrivalAt! - 1;
  const saved = encodeEconomy(economy);
  await page.addInitScript(({ key, saved }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, saved); }, { key: ECONOMY_SAVE_KEY, saved });
  const errors = await openGame(page);
  await expect.poll(async () => (await snapshot(page)).economy.story!.stage).toBe('trade');
  const guest = (await snapshot(page)).economy.story!.craftsmanId!;
  expect((await snapshot(page)).economy.upgrades.tools).toBe(0);
  await page.locator('#story-open').click();
  await page.locator('#story-find-npc').click();
  await page.locator(`[data-quest-npc="${guest}"]`).click();
  await expect(page.locator('#story-speaker')).toHaveText('木匠·阿榆');
  await expect(page.locator('#story-tools')).not.toBeVisible();
  await expect(page.locator('#story-report')).toBeInViewport();
  await page.screenshot({ path: info.outputPath('craftsman-dialogue.png') });
  await page.locator('#story-report').click();
  await page.setViewportSize({ width: 320, height: 568 });
  await expect(page.locator('#story-tools')).toBeInViewport();
  await expect(page.locator('#story-supplies')).toBeInViewport();
  await page.screenshot({ path: info.outputPath('craftsman-reward-choice-phone.png') });
  const before = (await snapshot(page)).economy.goods.map(g => g.id);
  await page.locator('#story-tools').click();
  await expect(page.locator('#story-dialog')).toHaveAttribute('data-stage', 'complete');
  await expect(page.locator('#story-receipt')).toContainText('第一章已完成并领奖');
  const finished = (await snapshot(page)).economy;
  expect(finished.upgrades.tools).toBe(1);
  expect(finished.recruitment.roster).toHaveLength(1);
  expect(finished.goods.filter(g => !before.includes(g.id)).map(g => [g.resource, g.amount])).toEqual([['wood', 12], ['iron', 8]]);
  await page.screenshot({ path: info.outputPath('first-caravan-complete.png') });
  await page.locator('#story-close').click();
  await expect(page.locator(`[data-resident="${finished.story!.craftsmanId}"]`)).toHaveText('木匠·阿榆');
  await page.locator('#settings').click(); await page.locator('#return-menu').click();
  await page.locator('#continue-save').click();
  await expect(page.locator('#loading')).toHaveAttribute('data-phase', 'playing', { timeout: 90_000 });
  const resumed = (await snapshot(page)).economy;
  expect(resumed.story).toEqual(finished.story);
  expect(resumed.recruitment.roster).toHaveLength(1);
  expect(resumed.upgrades.tools).toBe(1);
  await page.locator('#story-open').click();
  await expect(page.locator('#story-journal')).toContainText('已完成 · 已领奖');
  await expect(page.locator('#story-tools')).not.toBeVisible();
  expect(errors).toEqual([]);
});
